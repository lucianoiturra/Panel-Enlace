let conexion: { url: string; sql: ReturnType<typeof postgres> } | null = null;

function getClient(url: string) {
  // Un DATABASE_URL distinto apunta a otra base, así que el cliente anterior
  // deja de servir: se reemplaza y se cierra el pool que quedó atrás.
  if (conexion?.url !== url) {
    const anterior = conexion;
    conexion = {
      url,
      sql: postgres(url, {
        prepare: false,
        max: 1,
        connect_timeout: 10,
        idle_timeout: 20,
      }),
    };
    void anterior?.sql.end({ timeout: 5 }).catch(() => {});
  }
  return conexion.sql;
}

