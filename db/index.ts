export async function getDb() {
  const url = process.env.DATABASE_URL?.trim();
  if (!url) throw new Error("Falta configurar DATABASE_URL con la conexión de Supabase.");
  // Supabase is migrated separately in production. Running DDL during every
  // serverless cold start can leave concurrent requests waiting on table locks.
  if (!process.env.VERCEL) await prepararEsquema(url);
  return drizzle(getClient(url), { schema });
}
